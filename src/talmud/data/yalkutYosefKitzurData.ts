export function getRecommendedYalkutSimanByCurrentHour(): YalkutCuratedSiman {
  const now = new Date();
  const day = now.getDay(); // 5 = Friday, 6 = Saturday
  const hour = now.getHours();

  if (day === 5 && hour >= 13) {
    return (
      YALKUT_YOSEF_CURATED_SIMANIM.find((s) => s.simanNum === 263) ||
      YALKUT_YOSEF_CURATED_SIMANIM[0]
    );
  }
  if (day === 6) {
    return (
      YALKUT_YOSEF_CURATED_SIMANIM.find((s) => s.simanNum === 271) ||
      YALKUT_YOSEF_CURATED_SIMANIM[0]
    );
  }
  if (hour >= 5 && hour < 10) {
    return (
      YALKUT_YOSEF_CURATED_SIMANIM.find((s) => s.simanNum === 25) ||
      YALKUT_YOSEF_CURATED_SIMANIM[0]
    );
  }
  if (hour >= 10 && hour < 15) {
    return (
      YALKUT_YOSEF_CURATED_SIMANIM.find((s) => s.simanNum === 158) ||
      YALKUT_YOSEF_CURATED_SIMANIM[0]
    );
  }
  if (hour >= 15 && hour < 19) {
    return (
      YALKUT_YOSEF_CURATED_SIMANIM.find((s) => s.simanNum === 232) ||
      YALKUT_YOSEF_CURATED_SIMANIM[0]
    );
  }
  return (
    YALKUT_YOSEF_CURATED_SIMANIM.find((s) => s.id === 'yy-yd-89') ||
    YALKUT_YOSEF_CURATED_SIMANIM[0]
  );
}

