export function toHebrewDafNumber(num: number): string {
  const hundreds = ["", "ק", "ר", "ש", "ת"];
  const tens = ["", "י", "כ", "ל", "מ", "נ", "ס", "ע", "פ", "צ"];
  const ones = ["", "א", "ב", "ג", "ד", "ה", "ו", "ז", "ח", "ט"];
  const h = Math.floor(num / 100);
  const rem = num % 100;
  if (rem === 15) return `${hundreds[h]}ט״ו`;
  if (rem === 16) return `${hundreds[h]}ט״ז`;
  const t = Math.floor(rem / 10);
  const o = rem % 10;
  const raw = `${hundreds[h]}${tens[t]}${ones[o]}`;
  if (raw.length === 1) return `${raw}׳`;
  return `${raw.slice(0, -1)}״${raw.slice(-1)}`;
}

export function generateDafListForTractate(lastDaf: number): string[] {
  const out: string[] = [];
  for (let d = 2; d <= lastDaf; d++) {
    out.push(`${d}a`);
    out.push(`${d}b`);
  }
  return out;
}
