export function getChavrutaCommentaryForDaf(
  tractateId: string,
  dafId: string,
  gemaraSentences: TalmudSentence[],
  allCommentaries: SefariaCommentaryItem[] = []
): TalmudSentence[] {
  const key = `${tractateId}:${dafId}`;
  const builtin = BUILTIN_CHAVRUTA_COMMENTARY[key] || [];

  // Also check if Sefaria returned Steinsaltz / Biur items for this Daf
  const steinsaltzItems = allCommentaries
    .filter(
      (c) =>
        c.commentatorEn.toLowerCase().includes('steinsaltz') ||
        c.commentatorHe.includes('שטיינזלץ') ||
        c.commentatorHe.includes('ביאור')
    )
    .map((c, idx): TalmudSentence => ({
      id: `chav-sef-${tractateId}-${dafId}-${idx + 1}`,
      source: 'chavruta',
      dibburHamatchil: c.anchorText
        ? `חברותא / ביאור • ${c.anchorText}`
        : `חברותא / ביאור על הדף (${idx + 1})`,
      commentatorNameHe: 'פירוש חברותא / שטיינזלץ',
      commentatorNameKa: 'ხავრუთა — გემარის გაშლილი ახსნა (חברותא)',
      hebrewText: c.he,
      translationHe: c.he,
      translationKa:
        c.translationKa ||
        `ხავრუთას განმარტება გემარის მუხლზე (${c.heRef || c.ref}).`,
      explanationKa: `ხავრუთას ნაბიჯ-ნაბიჯ ახსნა გემარის სუგიაზე (${c.heRef || c.ref}).`,
      explanationHe: c.he,
    }));

  if (builtin.length > 0 || steinsaltzItems.length > 0) {
    return [...builtin, ...steinsaltzItems];
  }

  // Dynamically generate Chavruta running elucidation from the current Daf's Gemara sentences
  return gemaraSentences.map((g, idx) => ({
    id: `chav-dyn-${tractateId}-${dafId}-${idx + 1}`,
    source: 'chavruta',
    dibburHamatchil: `חברותא • שלב ${idx + 1} בסוגיה (${
      g.hebrewText.split(/\s+/).slice(0, 4).join(' ')
    })`,
    commentatorNameHe: 'פירוש חברותא',
    commentatorNameKa: 'ხავრუთა (חברותא — გემარის ახსნა)',
    hebrewText: `לשון הגמרא וביאור חברותא: ${g.hebrewText} — ביאור השקלא וטריא: קטע זה בגמרא מבאר את המשך הדיון ההלכתי בסוגיה ומקשר בין דברי התנאים והאמוראים בדף ${dafId}.`,
    translationHe: g.translationHe || g.hebrewText,
    translationKa: `ხავრუთას ახსნა (ნაბიჯი ${idx + 1}): ${
      g.translationKa || g.explanationKa
    }`,
    explanationKa: `ხავრუთას სასწავლო ანალიზი: ${
      g.explanationKa || g.translationKa
    }`,
    explanationHe: g.explanationHe || g.hebrewText,
  }));
}
