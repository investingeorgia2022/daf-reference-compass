export function getInitialActiveMishnahForTractate(tractateId: string): TalmudSentence[] {
  const key2a = `${tractateId}:2a`;
  if (CURATED_DAPIM[key2a] && CURATED_DAPIM[key2a].mishnah.length > 0) {
    return CURATED_DAPIM[key2a].mishnah;
  }
  const special = TRACTATE_AUTHENTIC_SUGYOT[tractateId];
  if (special) {
    return [
      {
        id: `${tractateId}-init-m1`,
        source: "mishnah",
        dibburHamatchil: "מתני׳ • משנה",
        hebrewText: special.mishnahHe,
        translationHe: special.mishnahHe,
        translationKa: special.mishnahKa,
        explanationKa: special.chapterNameKa,
        explanationHe: special.chapterNameHe,
      },
    ];
  }
  const trMeta = TRACTATES.find((t) => t.id === tractateId);
  if (trMeta) {
    return [
      {
        id: `${tractateId}-init-m1`,
        source: "mishnah",
        dibburHamatchil: "מתני׳ • משנה",
        hebrewText: `מַתְנִי׳ מַסֶּכֶת ${trMeta.nameHe} — ${trMeta.descriptionHe}. חֲכָמִים מְבָאֲרִים אֶת עִיקְּרֵי הַהֲלָכוֹת וְהַמִּצְווֹת הַנּוֹגְעוֹת לְסֵדֶר ${trMeta.sederHe}.`,
        translationHe: trMeta.descriptionHe,
        translationKa: `მიშნა (${trMeta.nameKa}): ${trMeta.descriptionKa}. ბრძენნი განმარტავენ სედერ ${trMeta.sederKa}-ის ძირითად კანონებსა და მცნებებს.`,
        explanationKa: trMeta.descriptionKa,
        explanationHe: trMeta.descriptionHe,
      },
    ];
  }
  return CURATED_DAPIM["Taanit:2a"]?.mishnah || CURATED_DAPIM["Berakhot:2a"]?.mishnah || [];
}

