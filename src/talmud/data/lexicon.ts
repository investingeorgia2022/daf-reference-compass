// Smart lookup that also strips common Hebrew/Aramaic prefixes (ו, ה, ב, כ, ל, מ, ד, ש)
export function lookupGeorgianLexicon(rawWord: string): LexiconEntry | undefined {
  const repaired = repairSiddurOcrWord(rawWord) || rawWord;
  const clean = normalizeHebrewWord(repaired);
  if (!clean) return undefined;
  if (SIDDUR_WORD_LEXICON[clean]) return SIDDUR_WORD_LEXICON[clean];
  if (TALMUD_LEXICON[clean]) return TALMUD_LEXICON[clean];

  const prefixes = ["ו", "ה", "ב", "כ", "ל", "מ", "ד", "ש", "וה", "בה", "כה", "לה", "מה", "דכ", "שכ"];
  for (const p of prefixes) {
    if (clean.startsWith(p) && clean.length - p.length >= 2) {
      const stem = clean.slice(p.length);
      if (SIDDUR_WORD_LEXICON[stem]) return SIDDUR_WORD_LEXICON[stem];
      if (TALMUD_LEXICON[stem]) return TALMUD_LEXICON[stem];
    }
  }
  return undefined;
}

export const findLexiconEntry = lookupGeorgianLexicon;

// Build an immediate Georgian glossary summary for any Hebrew sentence if AI response is loading
export function buildInstantGeorgianSentenceSummary(hebrewSentence: string): string {
  const words = hebrewSentence.split(/\s+/).filter(Boolean);
  const glosses: string[] = [];
  const seen = new Set<string>();
  for (const w of words) {
    const entry = lookupGeorgianLexicon(w);
    if (entry && !seen.has(entry.wordHe)) {
      seen.add(entry.wordHe);
      glosses.push(`${w}: ${entry.translationKa}`);
    }
    if (glosses.length >= 5) break;
  }
  if (glosses.length > 0) {
    return `ქართული განმარტება: ${glosses.join(" • ")}`;
  }
  return "მიმდინარეობს სრული ქართული თარგმანისა და თალმუდური განმარტების მომზადება...";
}
