/**
 * Finds the best matching SiddurPrayerSectionMeta for a given edition and page number
 */
export function findSiddurSectionForPage(
  editionId: SiddurEditionId,
  pageNumber: number
): SiddurPrayerSectionMeta {
  const exact = SIDDUR_PRAYER_SECTIONS.find((s) =>
    editionId === 'classic-siddur'
      ? s.classicPage === pageNumber
      : s.kavanatPage === pageNumber
  );
  if (exact) return exact;

  let best = SIDDUR_PRAYER_SECTIONS[0];
  let bestDist = Infinity;
  for (const s of SIDDUR_PRAYER_SECTIONS) {
    const p = editionId === 'classic-siddur' ? s.classicPage : s.kavanatPage;
    const dist = Math.abs(p - pageNumber);
    if (dist < bestDist) {
      bestDist = dist;
      best = s;
    }
  }
  return best;
}

