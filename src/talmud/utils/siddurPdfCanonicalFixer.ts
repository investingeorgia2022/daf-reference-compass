export function repairSiddurOcrWord(rawWord: string): string {
  if (!rawWord) return '';
  const trimmed = rawWord.replace(/^[^\u0590-\u05FF0-9]+|[^\u0590-\u05FF0-9]+$/g, '').trim();
  if (!trimmed) return rawWord;
  if (OCR_WORD_REPLACEMENTS[trimmed]) {
    return OCR_WORD_REPLACEMENTS[trimmed];
  }
  const plain = trimmed.replace(/[\u0591-\u05C7]/g, '');
  if (OCR_WORD_REPLACEMENTS[plain]) {
    return OCR_WORD_REPLACEMENTS[plain];
  }
  return trimmed
    .replace(/עז(?=[א-ת])/g, 'ש')
    .replace(/ננ(?=$|\s)/g, 'ם')
    .replace(/נל(?=[א-ת])/g, 'מ');
}

export function repairSiddurOcrLine(rawLine: string): string {
  if (!rawLine) return '';
  // Strip interlinear kabbalistic noise tokens that leaked into OCR
  const cleaned = rawLine
    .replace(/שויתי\s+י[הוהי]*\s+לנגדי\s+תמיד/g, ' ')
    .replace(/יאהדונהי/g, ' ')
    .replace(/היה\s+הוה\s+ויהיה/g, ' ')
    .replace(/תקיף\s*בעל\s*היכולת/g, ' ')
    .replace(/ובעל\s*הכ[יו]?[חת]ות\s*כולם/g, ' ')
    .replace(/המשגיח\s*עלינו\s*בפרט/g, ' ')
    .replace(/[^\u0590-\u05FF\s.,:;'"״׳()\-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  const words = cleaned.split(/\s+/).map((w) => {
    const punctPrefix = w.match(/^[("'״׳(\[]+/)?.[0] || '';
    const punctSuffix = w.match(/[)"'״׳.,:;!\]]+$/)?.[0] || '';
    const core = w.slice(punctPrefix.length, w.length - punctSuffix.length);
    const fixedCore = repairSiddurOcrWord(core);
    return `${punctPrefix}${fixedCore}${punctSuffix}`;
  });

  return words.join(' ').replace(/\s+/g, ' ').trim();
}

export function lookupSiddurLineTranslationKa(hebrewLine: string): string | null {
  if (!hebrewLine) return null;
  const repaired = repairSiddurOcrLine(hebrewLine);
  const normLine = normalizeHebrewWord(repaired);
  if (!normLine || normLine.length < 3) return null;

  for (const item of SIDDUR_CANONICAL_LINE_TRANSLATIONS_KA) {
    const normMatch = normalizeHebrewWord(item.matchHe);
    if (
      normLine === normMatch ||
      (normLine.length >= 6 && normMatch.includes(normLine)) ||
      (normMatch.length >= 6 && normLine.includes(normMatch))
    ) {
      return item.translationKa;
    }
  }
  return null;
}

export function matchCanonicalSiddurRow(
  tractateId: string,
  dafId: string,
  topPct: number
): CanonicalSiddurRowSpec | null {
  if (!tractateId.startsWith('Siddur_')) return null;
  const pageNum = parseInt(String(dafId).replace(/[^0-9]/g, ''), 10) || 29;
  const specs = CANONICAL_SIDDUR_PAGE_ROWS[pageNum];
  if (!specs || specs.length === 0) return null;

  let best: CanonicalSiddurRowSpec | null = null;
  let bestDiff = Infinity;
  for (const spec of specs) {
    const tol = spec.tolerancePct ?? 1.85;
    const diff = Math.abs(spec.topPct - topPct);
    if (diff <= tol && diff < bestDiff) {
      bestDiff = diff;
      best = spec;
    }
  }
  return best;
}
